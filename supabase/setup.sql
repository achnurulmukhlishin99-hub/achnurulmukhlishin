-- Jalankan sekali di Supabase > SQL Editor
create table public.certificates (
  id bigint generated by default as identity primary key,
  "Img" text not null,
  created_at timestamptz default now()
);
create table public.portfolio_comments (
  id uuid default gen_random_uuid() primary key,
  user_name text not null check (char_length(user_name) <= 40),
  content text not null check (char_length(content) <= 500),
  created_at timestamptz default now()
);
alter table public.certificates enable row level security;
alter table public.portfolio_comments enable row level security;
create policy "baca sertifikat" on public.certificates for select using (true);
create policy "baca komentar" on public.portfolio_comments for select using (true);
create policy "kirim komentar" on public.portfolio_comments for insert with check (true);
